import assert from 'node:assert/strict';
import { uploadComposerFile } from '../public/file-upload.js';
const file=new File(['content'],'测试.txt',{type:'text/plain'});
const calls=[];
const plan={upload:{url:'https://s3.example/upload',method:'PUT',headers:{'content-type':'text/plain','if-none-match':'*'}},ticket:'one-file-ticket'};
const api=async(path,options)=>{calls.push({path,options});return path==='/api/uploads'?plan:{url:'https://app.example/files/token/file.txt'}};
const fetchImpl=async(url,options)=>{calls.push({url,options});return {ok:true}};
assert.deepEqual(await uploadComposerFile(file,{api,fetchImpl,paneId:'%1',machineId:'offline-machine'}),{url:'https://app.example/files/token/file.txt'});
assert.deepEqual(JSON.parse(calls[0].options.body),{name:'测试.txt',size:7,contentType:'text/plain'});
assert.equal(calls[0].options.machineId,undefined,'direct upload does not depend on a machine');
assert.equal(calls[1].url,plan.upload.url);assert.equal(calls[1].options.body,file);
assert.equal(calls[1].options.credentials,'omit');assert.deepEqual(calls[1].options.headers,plan.upload.headers);
assert.equal(calls[2].path,'/api/uploads/complete');assert.deepEqual(JSON.parse(calls[2].options.body),{ticket:plan.ticket});
const prior=calls.length;
await assert.rejects(uploadComposerFile(file,{api,fetchImpl:async()=>({ok:false,status:403})}),/authorization expired/);
assert.equal(calls.length,prior+1,'failed uploads never complete');
let count=0;
const legacy=async(path,options)=>{if(count++===0)throw Object.assign(new Error(),{status:501});assert.ok(path.startsWith('/api/upload?'));assert.equal(options.body,file);assert.equal(options.machineId,'machine');return {path:'/tmp/file'}};
assert.deepEqual(await uploadComposerFile(file,{api:legacy,paneId:'%1',machineId:'machine'}),{path:'/tmp/file'});
await assert.rejects(uploadComposerFile(file,{api:async()=>{throw Object.assign(new Error('denied'),{status:403})}}),/denied/);
console.log('Browser direct upload: metadata → storage bytes → completion, credentials isolation, failure and legacy fallback passed.');
